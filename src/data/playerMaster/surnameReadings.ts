export function katakanaToHiragana(input: string): string {
  return input.replace(/[\u30a1-\u30f6]/g, (ch) =>
    String.fromCharCode(ch.charCodeAt(0) - 0x60),
  );
}

/** かなクエリから候補になる漢字名字を返す */
export function surnamesFromReading(query: string): string[] {
  const hira = katakanaToHiragana(query.trim());
  if (!hira) return [];
  const exact = SURNAME_READINGS[hira];
  if (exact) return exact;
  // 前方一致（「さと」→佐藤）
  const hits = new Set<string>();
  for (const [reading, names] of Object.entries(SURNAME_READINGS)) {
    if (reading.startsWith(hira) || hira.startsWith(reading)) {
      for (const n of names) hits.add(n);
    }
  }
  return [...hits];
}
